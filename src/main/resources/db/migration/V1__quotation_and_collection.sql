CREATE TABLE quotation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_date DATE NOT NULL,
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'EUR')),
    bulletin VARCHAR(16) NOT NULL CHECK (bulletin IN ('ABERTURA', 'ENCERRAMENTO')),
    purchase DECIMAL(38,18) NOT NULL CHECK (purchase > 0),
    sale DECIMAL(38,18) NOT NULL CHECK (sale > 0),
    quoted_at TIMESTAMP(9) NOT NULL,
    collected_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_quotation_item UNIQUE (quotation_date, currency, bulletin)
);

CREATE INDEX ix_quotation_history ON quotation (currency, quotation_date, bulletin);

CREATE TABLE collection_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_date DATE NOT NULL,
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('USD', 'EUR')),
    bulletin VARCHAR(16) NOT NULL CHECK (bulletin IN ('ABERTURA', 'ENCERRAMENTO')),
    state VARCHAR(16) NOT NULL CHECK (state IN ('PENDING', 'PROCESSING', 'COMPLETED')),
    created_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    first_attempt_at TIMESTAMP(9) WITH TIME ZONE,
    last_attempt_at TIMESTAMP(9) WITH TIME ZONE,
    next_attempt_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    claim_token UUID,
    claim_until TIMESTAMP(9) WITH TIME ZONE,
    last_outcome VARCHAR(32),
    last_error VARCHAR(256),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_collection_item UNIQUE (quotation_date, currency, bulletin)
);

CREATE INDEX ix_collection_due ON collection_item (state, quotation_date, next_attempt_at);